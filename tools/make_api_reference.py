"""Writes the Command reference of docs/API.md from qt_shell/api_reference.py (between the BEGIN / END markers).

    python3 tools/make_api_reference.py          # rewrite docs/API.md
    python3 tools/make_api_reference.py --check  # exit 1 when docs/API.md is out of date
"""
import importlib.util
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "API.md")
BEGIN, END = "<!-- BEGIN COMMAND REFERENCE (generated by tools/make_api_reference.py) -->", \
    "<!-- END COMMAND REFERENCE -->"

# how a script gets the object of a group's methods
HOLDER = {
    "timeline": "tl = qt_shell.api.timeline()",
    "outliner": "ol = qt_shell.api.outliner()",
    "graph": "ge = qt_shell.api.graph_editor()",
    "uv": "uv = qt_shell.api.uv_editor()  (UVCanvas: uv.canvas)",
    "render": "rv = qt_shell.api.render_view()",
    "player": "player = qt_shell.api.main_window().anim_player",
    "image": "ie = qt_shell.api.image_editor()",
    "sequencer": "vs = qt_shell.api.video_sequencer()",
}
MODULE = {"api": "qt_shell.api", "scripts": "qt_shell.scripts", "shelf": "qt_shell.shelf",
          "seq_export": "qt_shell.seq_export", "bluepencil": "qt_shell.bluepencil", "burnin": "qt_shell.burnin",
          "annotate": "qt_shell.annotate", "image_editor": "qt_shell.image_editor"}


def load():
    spec = importlib.util.spec_from_file_location("api_reference", os.path.join(ROOT, "qt_shell", "api_reference.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def slug(text):
    return re.sub(r"[^a-z0-9 _-]", "", text.lower()).strip().replace(" ", "-")


def full_name(c):
    parts = c["key"].split(".")
    if len(parts) == 2:                                  # module function
        return f'{MODULE.get(parts[0], "qt_shell." + parts[0])}.{c["synopsis"]}'
    return f'{parts[-2]}.{c["synopsis"]}'                # Class.method(...)


def title(c):
    parts = c["key"].split(".")
    return parts[-1] if len(parts) == 2 else f"{parts[-2]}.{parts[-1]}"


def build(m):
    out = [BEGIN, "", "## 15. Command reference", "",
           "Every command of the API on its own, like Maya's command documentation: synopsis, return value, "
           "description, parameters and an example you can paste into the **Console** or the **Text editor**. The "
           "same text appears in the Text editor's **Quick Help** (F1 on a name). The examples use `C:/out/…` and "
           "`C:/clips/…` for files – change the paths to yours. Every example marked ✔ is run by an automatic test "
           "in Blender 5.2.", ""]
    groups = [(g, t) for g, t in m.GROUPS if any(c["group"] == g for c in m.COMMANDS)]
    out.append(" · ".join(f"[{t}](#{slug('15 ' + t)})" for g, t in groups))
    out.append("")
    for g, t in groups:
        out += [f"### 15 {t}", ""]
        if g in HOLDER:
            out += [f"The methods below belong to the object you get with `{HOLDER[g]}`.", ""]
        cmds = [c for c in m.COMMANDS if c["group"] == g]
        out.append("| Command | Description |")
        out.append("|---|---|")
        for c in cmds:
            first = c["desc"].split(". ")[0].rstrip(".") + "."
            out.append(f"| [`{title(c)}`](#{slug(title(c))}) | {first} |")
        out.append("")
        for c in cmds:
            out += [f"#### {title(c)}", "", f"**Synopsis:** `{full_name(c)}`  ", f"**Returns:** {c['returns']}", "",
                    c["desc"], ""]
            if c["params"]:
                out += ["| Parameter | Type | Description |", "|---|---|---|"]
                out += [f"| `{n}` | {t} | {d} |" for n, t, d in c["params"]]
                out.append("")
            if c["example"]:
                tag = "✔ tested" if c["run"] else f"not run by the test – {c['skip']}"
                out += [f"**Example** ({tag})", "", "```python", c["example"], "```", ""]
    out.append(END)
    return "\n".join(out)


def main():
    m = load()
    doc = open(DOC, encoding="utf-8").read()
    block = build(m)
    if BEGIN in doc:
        a = doc.index(BEGIN)
        b = doc.index(END) + len(END)
        new = doc[:a] + block + doc[b:]
    else:
        new = doc.rstrip("\n") + "\n\n" + block + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if new == doc else 1)
    open(DOC, "w", encoding="utf-8").write(new)
    print(f"{len(m.COMMANDS)} commands written to {DOC}")


if __name__ == "__main__":
    main()
